def area(a):
    '''
    Возвращает площадь квадрата со стороной a.

            Параметры:
                    a (int | float): размер стороны квадрата

            Возвращаемое значение:
                    (int | float): площадь квадрата
    '''
    return a * a


def perimeter(a):
    '''
    Возвращает периметр квадрата со стороной a.

            Параметры:
                    a (int | float): размер стороны квадрата

            Возвращаемое значение:
                    (int | float): периметр квадрата
    '''
    return 4 * a
