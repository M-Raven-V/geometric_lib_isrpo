import math

def area(r):
    ''' 
    Возвращает площадь окружности радиусом r.

            Параметры: 
                    r (int | float): число, равное радиусу окружности
           
            Возвращаемое значение:
                    (float): число, равное площади окружности радиусом r
    '''
    return math.pi * r * r 


def perimeter(r):
    '''
    Возвращает длину окружности радиусом r.

            Параметры: 
                    r (int | float): число, равное радиусу окружности

            Возвращаемое значение:
                    (float): число, равное длине окружности радиусом r   
    '''
    return 2 * math.pi * r